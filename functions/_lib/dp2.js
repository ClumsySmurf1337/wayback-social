// DP2 licence keys — shared by functions/api/paddle-webhook.js and
// functions/api/licence-check.js. Node crypto only, no dependencies.
//
// Format: DP2-<TIER>-<16 random base32>-<86 base64url Ed25519 sig>
// (86, not 88: a 64-byte Ed25519 signature is 88 base64url chars
// WITH padding, but both this file (Buffer base64url) and
// licence2.py (_b64url) strip the padding — the minted keys are 86
// chars, verified live 2026-11-27. The "86-char signature" error
// message below was always right; the "88" in this comment was the
// wrong half. licence2.py's docstring said 88 too (contradicting its
// own "<86 chars>" example) — fixed there 2026-11-27, comment-only.)
// Signature is over the bytes "DP2:<TIER>:<RANDOM>".
// The private key (PEM, PKCS#8) comes from the Pages secret
// LICENCE_ED25519_PRIVATE_KEY. The public key (SPKI DER base64) is
// baked into wayback_social/licence2.py and web/licence.js — the
// same keypair, generated by scripts/gen_licence_keys.mjs.
//
// NOTE: files under functions/_lib/ are ignored by the Pages
// Functions router (underscore prefix) — this is not a route.
import { createPrivateKey, createPublicKey, sign, verify, timingSafeEqual } from "node:crypto";

const TIERS = new Set(["free", "starter", "pro", "studio"]);

export function payload(tier, random) {
  return Buffer.from(`DP2:${tier.toUpperCase()}:${random}`, "utf8");
}

function random16() {
  const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567";
  const bytes = new Uint8Array(10);
  crypto.getRandomValues(bytes);
  let random = "", acc = 0, bits = 0;
  for (const b of bytes) {
    acc = (acc << 8) | b; bits += 8;
    while (bits >= 5) { random += alphabet[(acc >> (bits - 5)) & 31]; bits -= 5; }
  }
  if (bits > 0) random += alphabet[(acc << (5 - bits)) & 31];
  return random.slice(0, 16);
}

function b64url(buf) {
  return Buffer.from(buf).toString("base64url");
}

/** Mint a DP2 key for a tier. privateKeyPem = PKCS#8 PEM string. */
export function mintKey(tier, privateKeyPem) {
  const t = (tier || "").toLowerCase();
  if (!TIERS.has(t)) throw new Error(`unknown tier: ${tier}`);
  const random = random16();
  const key = createPrivateKey(privateKeyPem);
  const sig = sign(null, payload(t, random), key);
  return `DP2-${t.toUpperCase()}-${random}-${b64url(sig)}`;
}

/** Verify a DP2 key against a public key (KeyObject, PEM string, or SPKI DER base64). */
export function verifyKey(key, publicKey) {
  // The base64url signature alphabet includes "-", so split into at
  // most 4 parts and rejoin the rest — the signature is always last.
  const rawParts = (key || "").trim().split("-");
  if (rawParts.length < 4 || rawParts[0] !== "DP2") return { valid: false, tier: null, reason: "malformed key — expected DP2-<TIER>-<16 chars>-<86-char signature>" };
  const parts = [rawParts[0], rawParts[1], rawParts[2], rawParts.slice(3).join("-")];
  const tier = parts[1].toLowerCase();
  if (!TIERS.has(tier) || parts[2].length !== 16 || !/^[A-Z0-9]+$/.test(parts[2])) {
    return { valid: false, tier: null, reason: "malformed key — bad tier or random part" };
  }
  let sig;
  try {
    sig = Buffer.from(parts[3], "base64url");
  } catch {
    return { valid: false, tier: null, reason: "malformed key — bad signature encoding" };
  }
  if (sig.length !== 64) return { valid: false, tier: null, reason: "malformed key — signature must be 64 bytes" };
  let pub;
  try {
    pub = typeof publicKey === "string" && publicKey.includes("-----BEGIN")
      ? createPublicKey(publicKey)
      : createPublicKey({ key: Buffer.from(publicKey, "base64"), format: "der", type: "spki" });
  } catch {
    return { valid: false, tier: null, reason: "production public key not configured" };
  }
  const ok = verify(null, payload(tier, parts[2]), pub, sig);
  return ok
    ? { valid: true, tier, reason: "valid" }
    : { valid: false, tier: null, reason: "signature mismatch — not minted with the production key" };
}

/** SHA-256 hex of the full key — what D1 stores (never the key itself). */
export async function keyHash(key) {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(key.trim()));
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

